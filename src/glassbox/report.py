"""Report aggregation: findings in, deterministic Markdown + JSON out.

Deterministic ordering (severity, then rule id, then target) means two reports
from the same findings diff cleanly in git - useful when a retest shows what
changed between engagements.
"""

from __future__ import annotations

import json
from collections import Counter
from dataclasses import asdict
from datetime import UTC, datetime

from .probe import Finding

SEVERITY_ORDER = {"high": 0, "medium": 1, "low": 2, "info": 3}


def sort_findings(findings: list[Finding]) -> list[Finding]:
    """Severity first (high to info), then rule id, then target - stable and total."""
    return sorted(
        findings,
        key=lambda f: (SEVERITY_ORDER.get(f.severity, 99), f.rule_id, f.target),
    )


def to_markdown(findings: list[Finding], target: str, engagement: str = "unnamed") -> str:
    """Render findings as a Markdown report with a summary table."""
    ordered = sort_findings(findings)
    counts = Counter(f.severity for f in ordered)
    generated = datetime.now(UTC).isoformat(timespec="seconds")

    lines = [
        f"# Glassbox report - {target}",
        "",
        f"- Engagement: {engagement}",
        f"- Generated (UTC): {generated}",
        f"- Total findings: {len(ordered)}",
        f"- high: {counts.get('high', 0)} | medium: {counts.get('medium', 0)} | "
        f"low: {counts.get('low', 0)} | info: {counts.get('info', 0)}",
        "",
        "## Findings",
        "",
    ]
    if not ordered:
        lines.append("No findings - either the target is hardened or nothing was tested.")
        lines.append("")
    for finding in ordered:
        lines += [
            f"### [{finding.severity.upper()}] {finding.rule_id}",
            "",
            f"- Target: `{finding.target}`",
            f"- Observed: {finding.description}",
            f"- Evidence: `{finding.evidence}`",
            f"- Fix: {finding.remediation}",
            "",
        ]
    lines += [
        "---",
        "",
        "Generated by glassbox-recon. Every evidence line above traces to an "
        "actual response or file read - nothing here is inferred.",
    ]
    return "\n".join(lines)


def to_json(findings: list[Finding], target: str, engagement: str = "unnamed") -> str:
    """Render findings as pretty-printed JSON for downstream automation."""
    payload = {
        "target": target,
        "engagement": engagement,
        "generated_utc": datetime.now(UTC).isoformat(timespec="seconds"),
        "counts": dict(Counter(f.severity for f in findings)),
        "findings": [asdict(f) for f in sort_findings(findings)],
    }
    return json.dumps(payload, indent=2, ensure_ascii=False)
